const { chromium } = require('../../fevoco-managment/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const base = process.env.TERRITORY_TEST_URL || 'http://127.0.0.1:3016'
const out = path.join(__dirname, '../docs/territory-qa')
;(async()=>{
 await fs.mkdir(out,{recursive:true})
 const browser = await chromium.launch({headless:true})
 const context = await browser.newContext({viewport:{width:1440,height:1000}})
 const page = await context.newPage()
 page.setDefaultTimeout(300000)
 const report={checks:[],screenshots:[],errors:[],interceptedWrites:0}
 const record=(s)=>{report.checks.push(s);console.log(s)}
 page.on('pageerror',e=>report.errors.push(e.message))
 try {
  const response=await context.request.get(base+'/api/ligues',{timeout:300000})
  const data=await response.json()
  assert.equal(response.status(),200,data.message)
  assert.equal(data.ligues.length,26)
  assert.deepEqual(data.ligues.map(l=>l.idLigue),Array.from({length:26},(_,i)=>String(i+1).padStart(2,'0')))
  assert.ok(data.ligues.every(l=>l.statut===''))
  report.source=data.source; record('API '+data.source+' : 26 ligues, codes 01-26 et statuts vides')
  for(const kind of ['ententes','clubs']){
   const r=await context.request.get(base+'/api/'+kind,{timeout:60000})
   assert.equal(r.status(),200);assert.equal((await r.json())[kind].length,0)
   record('API '+data.source+' : '+kind+' vide')
  }
  for (const url of ['/api/ligues/01','/api/ententes/0101','/api/clubs/0101001']) { const warm=await context.request.get(base+url,{timeout:300000}); assert.ok(warm.headers()['content-type']?.includes('application/json')); assert.equal(warm.status(),url.includes('/ligues/')?200:404) }
  const denied=await context.request.post(base+'/api/ligues',{headers:{origin:'https://exemple.invalid'},data:{},timeout:300000})
  assert.equal(denied.status(),403)
  record('API : origine externe refusee avant mutation')
  const savedEntente={id:'0101',idEntente:'0101',codeEntente:'01',nomEntente:'Entente test simulee',pseudoEntente:'TEST',idLigue:'01',nomLigue:data.ligues[0].nomLigue,provinceId:'PRO01',provinceNom:'KINSHASA',emailEntente:'',idVille:'',observations:'',numeroOrdre:'01',nom:'Entente test simulee',pseudo:'TEST',ligueId:'01',ligueNom:data.ligues[0].nomLigue,statut:''}
  // In Sheets mode every browser mutation is intercepted; test mode uses the in-memory adapter.
  if(data.source !== 'test') await context.route('**/api/**',async route=>{
   const req=route.request()
   if(['GET','HEAD','OPTIONS'].includes(req.method())) return route.continue()
   report.interceptedWrites++
   const payload=req.postDataJSON()||{}
   let body={message:'Test simule uniquement'}
   if(new URL(req.url()).pathname.startsWith('/api/ligues/')) body.ligue={...data.ligues[0],...payload,nom:payload.nomLigue}
   else if(new URL(req.url()).pathname.startsWith('/api/ententes')) body.entente={...savedEntente,...payload,nom:payload.nomEntente}
   else return route.fulfill({status:409,json:{message:'Test non autorise'}})
   return route.fulfill({status:req.method()==='POST'?201:200,json:body})
  })
  if (!process.argv.includes('--from-ententes')) {
  await page.goto(base+'/ligues',{waitUntil:'load',timeout:300000})
  await page.getByText('sur 26 resultats',{exact:false}).count().catch(()=>0)
  assert.match(await page.locator('body').innerText(),/sur 26 résultat/)
  const search=page.getByPlaceholder('Rechercher une ligue...')
  await search.fill('KINSHASA')
  await page.waitForFunction(()=>document.body.innerText.includes('sur 1 r\u00e9sultat'))
  assert.match(await page.locator('body').innerText(),/sur 1 résultat/)
  await search.fill('AUCUN_RESULTAT_TEST')
  await page.locator('p:visible,td:visible').filter({hasText:/^Aucune donnée trouvée$/}).waitFor()
  await search.fill('')
  await page.getByRole('combobox').last().click()
  await page.getByRole('option',{name:'50',exact:true}).click()
  await page.waitForFunction(()=>document.querySelectorAll('tbody tr').length===26)
  assert.equal(await page.locator('tbody tr').count(),26)
  await page.screenshot({path:path.join(out,'ligues-desktop.png'),fullPage:true})
  report.screenshots.push('ligues-desktop.png')
  record('UI ligues : recherche, vide, pagination 50 et 26 lignes visibles')
  await page.getByRole('button',{name:'Voir '+data.ligues[0].nomLigue,exact:true}).first().click()
  await page.getByRole('heading',{name:/Fiche Ligue/}).waitFor()
  await page.screenshot({path:path.join(out,'ligue-detail.png'),fullPage:true})
  await page.getByRole('button',{name:'Modifier '+data.ligues[0].nomLigue,exact:true}).first().click()
  await page.getByRole('dialog').waitFor()
  assert.equal(await page.getByRole('dialog').getByLabel('Identifiant',{exact:true}).inputValue(),'01')
  assert.match(await page.getByRole('dialog').getByLabel('Statut',{exact:true}).innerText(),/Non renseigné/)
  await page.getByRole('dialog').getByLabel('Nom de la ligue').fill('Ligue test simulee')
  await page.getByRole('button',{name:'Enregistrer',exact:true}).click()
  await page.getByRole('dialog').waitFor({state:'hidden'})
  record('UI ligue : fiche, statut vide et modification simulee avec ID 01 conserve')
  }
  await page.goto(base+'/ententes',{waitUntil:'load',timeout:300000})
  await page.locator('p:visible,td:visible').filter({hasText:/^Aucune donnée trouvée$/}).waitFor()
  await page.screenshot({path:path.join(out,'ententes-vide.png'),fullPage:true})
  await page.getByRole('button',{name:'Ajouter une entente',exact:true}).click()
  await page.getByRole('dialog').getByLabel('Code de l’entente').fill('01')
  await page.getByRole('dialog').getByLabel('Ligue',{exact:false}).click()
  await page.getByRole('option',{name:/^01 /}).click()
  await page.getByRole('dialog').getByLabel('Nom de l’entente').fill('Entente test simulee')
  await page.getByRole('button',{name:'Enregistrer',exact:true}).click()
  await page.getByRole('dialog').waitFor({state:'hidden'})
  await page.getByRole('button',{name:'Voir Entente test simulee',exact:true}).first().click()
  await page.getByRole('heading',{name:/Fiche Entente/}).waitFor()
  await page.getByRole('button',{name:'Modifier Entente test simulee',exact:true}).first().click()
  assert.ok(await page.getByRole('dialog').getByLabel('Code de l’entente').isDisabled())
  assert.ok(await page.getByRole('dialog').getByLabel('Ligue',{exact:false}).isDisabled())
  await page.getByRole('dialog').getByLabel('Nom de l’entente').fill('Entente test modifiee')
  await page.getByRole('button',{name:'Enregistrer',exact:true}).click()
  await page.getByRole('dialog').waitFor({state:'hidden'})
  record('UI entente : etat vide, creation et modification simulees, parent/code verrouilles')
  await page.goto(base+'/clubs',{waitUntil:'load',timeout:300000})
  await page.locator('p:visible,td:visible').filter({hasText:/^Aucune donnée trouvée$/}).waitFor()
  await page.screenshot({path:path.join(out,'clubs-vide.png'),fullPage:true})
  await page.getByRole('button',{name:'Ajouter un club',exact:true}).click()
  await page.getByRole('dialog').getByLabel('Ligue',{exact:false}).click()
  await page.getByRole('option',{name:/^01 /}).click()
  if(data.source==='test') {
   await page.getByRole('dialog').getByLabel('Entente',{exact:false}).click()
   await page.getByRole('option',{name:/^0101 /}).click()
   await page.getByRole('dialog').getByLabel('Code du club').fill('001')
   await page.getByRole('dialog').getByLabel('Nom du club').fill('Club test simule')
   await page.getByRole('button',{name:'Enregistrer',exact:true}).click()
   await page.getByRole('dialog').waitFor({state:'hidden'})
   await page.getByRole('button',{name:'Voir Club test simule',exact:true}).first().click()
   await page.getByRole('heading',{name:/Fiche Club/}).waitFor()
   await page.getByRole('button',{name:'Modifier',exact:true}).first().click()
   assert.equal(await page.getByRole('dialog').getByLabel('Identifiant',{exact:true}).inputValue(),'0101001')
   assert.ok(await page.getByRole('dialog').getByLabel('Code du club').isDisabled())
   assert.ok(await page.getByRole('dialog').getByLabel('Entente',{exact:false}).isDisabled())
   await page.getByRole('dialog').getByLabel('Nom du club').fill('Club test modifie')
   await page.getByRole('button',{name:'Enregistrer',exact:true}).click()
   await page.getByRole('dialog').waitFor({state:'hidden'})
   const saved=await (await context.request.get(base+'/api/clubs',{timeout:300000})).json()
   assert.equal(saved.clubs[0].idClub,'0101001');assert.equal(saved.clubs[0].idLigue,'01')
   assert.equal(saved.clubs[0].nomClub,'Club test modifie')
   await page.screenshot({path:path.join(out,'club-detail-test.png'),fullPage:true})
   record('UI club test : creation, fiche et modification persistantes en memoire, ID et parent conserves')
  } else {
   await page.getByText('Aucune entente dans cette ligue.',{exact:false}).waitFor()
   await page.keyboard.press('Escape')
   await page.getByRole('dialog').waitFor({state:'hidden'})
  }
  for(const kind of ['ligues','ententes','clubs']) {
   await page.setViewportSize({width:390,height:844})
   await page.goto(base+'/'+kind,{waitUntil:'load',timeout:300000})
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth))
   await page.screenshot({path:path.join(out,kind+'-mobile.png'),fullPage:true})
   record('Mobile sans debordement : '+kind)
  }
  assert.equal(report.errors.length,0,report.errors.join('\n'))
  record('Aucune erreur JavaScript')
 } catch(error) { report.failure=error.message; report.alerts=await page.getByRole('alert').allTextContents().catch(()=>[]); await page.screenshot({path:path.join(out,'failure.png'),fullPage:true}).catch(()=>{}); throw error } finally {await fs.writeFile(path.join(out,'results.json'),JSON.stringify(report,null,2));await browser.close()}
})().catch(e=>{console.error(e.message);process.exitCode=1})