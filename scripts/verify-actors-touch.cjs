const assert=require('node:assert/strict')
const fs=require('node:fs')
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'../../fevoco-managment/node_modules/playwright')
;(async()=>{
 const browser=await chromium.launch({headless:true})
 try {
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  const page=await context.newPage();page.setDefaultTimeout(120000)
  await page.route('**/api/**',route=>['POST','PATCH','DELETE'].includes(route.request().method())?route.abort():route.continue())
  await page.goto((process.env.ACTORS_QA_URL||'http://127.0.0.1:3027')+'/athletes',{waitUntil:'domcontentloaded',timeout:600000})
  const size=page.getByRole('combobox',{name:'Nombre de lignes',exact:true})
  await size.getByText('10',{exact:true}).waitFor()
  await size.tap();await page.getByRole('option',{name:'25',exact:true}).tap()
  await page.getByRole('button',{name:/^Voir /}).first().tap()
  await page.getByRole('button',{name:/^Modifier/}).first().tap()
  const dialog=page.getByRole('dialog');await dialog.waitFor()
  await dialog.getByRole('button',{name:'Annuler',exact:true}).tap();await dialog.waitFor({state:'hidden'})
  await page.getByRole('button',{name:/Retour.*la liste/}).tap()
  assert.ok((await size.textContent()).includes('25'))
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  fs.mkdirSync('docs/actors-qa',{recursive:true})
  await page.screenshot({path:'docs/actors-qa/athletes-touch.png',fullPage:true})
  console.log('PASS touch: pagination, detail, identity panel, cancellation, return state, no overflow')
 } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})